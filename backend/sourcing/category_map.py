def infer_category(title: str) -> str | None:
    """从标题推断白名单类目；无法映射 → None。

    - 标题清洗：去空白、去「价格带 ¥xx」尾缀干扰（不含关键词的正常命中不受影响）；
    - 子串匹配（小写），按 CATEGORY_KEYWORDS 顺序返回首个命中类目；
    - 无命中 → None（合规层按「白名单外/未知」处理）。
    """
    if not title:
        return None
    lower = (title or "").lower()
    for category, kws in CATEGORY_KEYWORDS.items():
        for kw in kws:
            if kw in lower:
                return category
    return None
